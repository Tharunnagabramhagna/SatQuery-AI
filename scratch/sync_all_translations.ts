const langs = ['en', 'es', 'fr', 'de', 'hi', 'ja'] as const;
const baseDicts = { en, es, fr, de, hi, ja };

for (const lang of langs) {
  const merged: any = { ...baseDicts[lang] };
  const langUpdates = updates[lang];

  for (const [section, sectionUpdates] of Object.entries(langUpdates)) {
    if (!merged[section]) {
      merged[section] = sectionUpdates;
    } else {
      merged[section] = {
        ...merged[section],
        ...(sectionUpdates as object),
      };
    }
  }

  const content = `import type { TranslationSchema } from '../types';\n\nexport const ${lang}: TranslationSchema = ${JSON.stringify(
    merged,
    null,
    2
  )};\n`;

  writeFileSync(`src/i18n/translations/${lang}.ts`, content, 'utf-8');
  console.log(`Updated src/i18n/translations/${lang}.ts`);
}

